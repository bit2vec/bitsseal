class DNATokenDataset(Dataset):
    """Sliding-window samples over a single concatenated DNA k-mer token stream."""
    def __init__(self, tokens_arr, seq_length=256, stride=128, max_samples=None):
        self.tokens = tokens_arr
        self.seq_length = seq_length
        self.stride = stride
        L = len(tokens_arr)
        n_p = (L - seq_length) // stride
        self._n = min(n_p, max_samples) if max_samples else max(n_p, 0)
        print(f'  DNA samples: {self._n:,} (corpus length {L:,})', flush=True)

    def __len__(self): return self._n

    def __getitem__(self, i):
        s = i * self.stride
        x = torch.as_tensor(self.tokens[s:s + self.seq_length].copy(), dtype=torch.long)
        y = torch.as_tensor(self.tokens[s + 1:s + self.seq_length + 1].copy(),
                             dtype=torch.long)
        return {'input_ids': x, 'labels': y}


