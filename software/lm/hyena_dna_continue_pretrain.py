#!/usr/bin/env python3
"""Continue pretraining a Hyena+Bits LM on DNA k-mer corpus, starting from
an existing checkpoint (e.g. our WikiText Bits LM).

Phase 2A: continue causal LM pretraining on hg38 chromosomes (or any DNA corpus)
          at k=6 mer tokenization. Loads body weights + Bits FFN from a
          previous WikiText checkpoint, regenerates the bit-mapping table for
          the new vocab (4096 k-mers), re-initializes the LM head for the new
          vocab.

Phase 2B (this same script's --finetune option): fine-tune the resulting
checkpoint on GB human_promoters at k=6.

Usage:
    # Continue pretrain on chr22:
    python hyena_dna_continue_pretrain.py --phase pretrain \\
        --pretrain_init /path/to/wikitext_pretrain.pt \\
        --chroms chr22 --n_epochs 5 \\
        --out_dir results/multimodality/hyena_dna_continue/chr22

    # Fine-tune on GB:
    python hyena_dna_continue_pretrain.py --phase finetune \\
        --pretrain_init results/multimodality/hyena_dna_continue/chr22/dna_pretrain.pt \\
        --out_dir results/multimodality/hyena_dna_continue/chr22
"""
