def transfer_text_pretrain_to_dna_lm(model, text_state, verbose=True):
    """Copy compatible weights from a text (BPE-50K) pretrain into the new
    DNA-vocab causal LM. Skip lm_head (vocab size differs) and
    subword2binary/subword (regenerated by the new Bits encoder constructor)."""
    md = model.state_dict()
    transferred, skipped = [], []
    for k, v in text_state.items():
        if 'subword2binary' in k or 'subword2bytes' in k or 'subword' in k:
            skipped.append((k, 'vocab-dependent buffer (regenerated)'))
            continue
        if k.startswith('lm_head.'):
            skipped.append((k, 'LM head re-initialized for new vocab'))
            continue
        if k in md and md[k].shape == v.shape:
            md[k] = v.clone()
            transferred.append((k, tuple(v.shape)))
        else:
            skipped.append((k, f'shape mismatch (was {tuple(v.shape)}, '
                              f'now {tuple(md[k].shape) if k in md else "absent"})'))
    model.load_state_dict(md, strict=False)
    if verbose:
        n_t = sum(int(np.prod(t[1])) for t in transferred)
        print(f'  transferred {len(transferred)} tensors ({n_t:,} params)',
              flush=True)
        print(f'  skipped {len(skipped)} tensors:', flush=True)
        for k, r in skipped[:8]:
            print(f'    SKIP: {k}  ({r})', flush=True)


def pretrain(args):
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    print(f'device={device}', flush=True)
    print(f'pretrain_init={args.pretrain_init}', flush=True)
    print(f'chroms={args.chroms}', flush=True)

    random.seed(args.seed); np.random.seed(args.seed); torch.manual_seed(args.seed)
    if torch.cuda.is_available(): torch.cuda.manual_seed(args.seed)

    # Build DNA k-mer corpus
    print('\n[corpus] building DNA k-mer corpus...', flush=True)
    tokens_arr, stoi = hg38_loader.build_corpus(args.chroms, k=args.k,
                                                  stride=args.kmer_stride)
    vocab_size = len(stoi)

    # Optional 5% validation split (stride-based, deterministic)
    val_cut = int(0.95 * len(tokens_arr))
    train_arr = tokens_arr[:val_cut]
    val_arr = tokens_arr[val_cut:]
    train_ds = DNATokenDataset(train_arr, seq_length=args.seq_length,
                                stride=args.stride, max_samples=args.max_samples)
    val_ds = DNATokenDataset(val_arr, seq_length=args.seq_length,
                              stride=args.seq_length)

    # Build model with new DNA vocab
    print('\n[model] building Hyena+Bits with DNA vocab...', flush=True)
    model, config = build_hyena_causal_lm(vocab_size, args.encoder,
                                            num_bits=args.num_bits,
                                            interdim=args.interdim,
                                            dropout=args.dropout,
                                            max_seq_len=args.seq_length)
    n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f'  params: {n_params:,}, d_model={config.d_model}, '
          f'n_layer={config.n_layer}, vocab={config.vocab_size}', flush=True)

    # Load text-pretrain weights
    if args.pretrain_init and args.pretrain_init.lower() != 'none':
        if not os.path.exists(args.pretrain_init):
            raise FileNotFoundError(args.pretrain_init)
        print(f'\n[init] loading {args.pretrain_init}', flush=True)
        ck = torch.load(args.pretrain_init, map_location='cpu', weights_only=False)
        text_state = ck.get('model_state_dict', ck)
        transfer_text_pretrain_to_dna_lm(model, text_state)
    else:
        print('\n[init] random init (no pretrain checkpoint)', flush=True)

    model = model.to(device)

    # Train
    tr = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                     num_workers=2, pin_memory=True)
    va = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False,
                     num_workers=2, pin_memory=True)
    opt = optim.AdamW(model.parameters(), lr=args.lr, weight_decay=0.01,
                      betas=(0.9, 0.98))
    crit = nn.CrossEntropyLoss()
    n_steps_per_epoch = len(tr)
    total_steps = args.n_epochs * n_steps_per_epoch
    sched = optim.lr_scheduler.OneCycleLR(opt, max_lr=args.lr,
                                            total_steps=max(total_steps, 1),
                                            pct_start=0.05)
    print(f'\n[train] {n_steps_per_epoch} steps/epoch, {total_steps} total',
          flush=True)

    best_ppl = float('inf')
    t0 = time.time()
    for ep in range(args.n_epochs):
        model.train()
        running = 0.0; n_batch = 0
        ep_t0 = time.time()
        for step, batch in enumerate(tr):
            ids = batch['input_ids'].to(device, non_blocking=True)
            lab = batch['labels'].to(device, non_blocking=True)
            opt.zero_grad()
            with torch.autocast(device_type='cuda', dtype=torch.bfloat16):
                logits = model(input_ids=ids).logits
                loss = crit(logits.reshape(-1, logits.size(-1)),
                            lab.reshape(-1))
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step(); sched.step()
            running += float(loss.item()); n_batch += 1
            if step % max(1, n_steps_per_epoch // 5) == 0:
                print(f'  ep {ep+1} step {step}/{n_steps_per_epoch} '
                      f'loss={loss.item():.3f}', flush=True)
            # Mid-epoch checkpoint (resume safety on long pretrains)
            ckpt_every = getattr(args, 'ckpt_every', 0)
            if ckpt_every > 0 and step > 0 and step % ckpt_every == 0:
                torch.save({'model_state_dict':
                            {k: v.detach().cpu().clone()
                             for k, v in model.state_dict().items()},
                            'config': vars(args), 'vocab_size': vocab_size,
                            'epoch': ep + 1, 'step': step, 'kmer_k': args.k,
                            'partial': True},
                           os.path.join(args.out_dir, 'dna_pretrain_partial.pt'))
                print(f'  [ckpt] saved partial at ep {ep+1} step {step}',
                      flush=True)
        # validate
        model.eval()
        v_loss = 0.0; v_n = 0
        with torch.no_grad(), torch.autocast(device_type='cuda', dtype=torch.bfloat16):
            for batch in va:
                ids = batch['input_ids'].to(device); lab = batch['labels'].to(device)
                logits = model(input_ids=ids).logits
                v_loss += float(crit(logits.reshape(-1, logits.size(-1)),
                                     lab.reshape(-1)).item()) * lab.size(0)
                v_n += lab.size(0)
        v_ppl = float(np.exp(v_loss / max(v_n, 1)))
        ep_time = time.time() - ep_t0
        print(f'  ep {ep+1}/{args.n_epochs}  train_loss='
              f'{running/max(n_batch,1):.3f}  val_ppl={v_ppl:.2f}  '
              f'({ep_time:.1f}s)', flush=True)
        if v_ppl < best_ppl:
            best_ppl = v_ppl
            torch.save({'model_state_dict': {k: v.detach().cpu().clone()
                                              for k, v in model.state_dict().items()},
                        'config': vars(args), 'vocab_size': vocab_size,
                        'val_ppl': v_ppl, 'epoch': ep + 1, 'kmer_k': args.k},
                       os.path.join(args.out_dir, 'dna_pretrain.pt'))
    print(f'\npretrain done in {time.time() - t0:.1f}s, best val PPL={best_ppl:.2f}',
          flush=True)
    return os.path.join(args.out_dir, 'dna_pretrain.pt')


